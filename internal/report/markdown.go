package report

import (
	"bufio"
	"fmt"
	"io"
	"strings"

	"github.com/Josperdo/ssotrace/internal/diagnose"
)

// Markdown writes the report for pasting into a ticket, chat, or pull
// request. It carries the same findings as Text, but every problem gets
// its full explanation, because the reader of a ticket may not have
// ssotrace or the HAR at hand.
func Markdown(w io.Writer, r *Report) error {
	bw := bufio.NewWriter(w)
	p := func(format string, a ...any) { _, _ = fmt.Fprintf(bw, format, a...) }

	c := r.counts()
	p("## ssotrace report: %s\n\n", mdText(r.File))
	p("**Result:** %s · %s\n", summaryLine(c), r.loginCount())

	for _, s := range r.sections() {
		p("\n### %s\n\n", mdText(s.Title))
		if len(s.Findings) == 0 {
			p("✅ No problems found.\n")
			continue
		}
		for i, f := range s.Findings {
			if i > 0 {
				p("\n")
			}
			mdFinding(p, f)
		}
	}

	footer := "Generated by ssotrace"
	if r.Version != "" {
		footer += " " + mdText(r.Version)
	}
	p("\n---\n<sub>%s. Values from the capture are shown as code; secrets are previewed, never shown in full.</sub>\n", footer)
	if err := bw.Flush(); err != nil {
		return fmt.Errorf("write markdown report: %w", err)
	}
	return nil
}

var mdSeverity = map[diagnose.Severity]string{
	diagnose.Fail: "❌ FAIL",
	diagnose.Warn: "⚠️ WARN",
	diagnose.Info: "ℹ️ INFO",
}

func mdFinding(p func(string, ...any), f diagnose.Finding) {
	p("#### %s · %s · %s\n\n", mdSeverity[f.Severity], f.RuleID, mdText(f.Title))
	if f.Detail != "" {
		p("%s\n\n", mdText(f.Detail))
	}
	if len(f.Evidence) > 0 {
		p("| Evidence | Value |\n|---|---|\n")
		for _, e := range f.Evidence {
			p("| %s | %s |\n", mdText(e.Label), mdCode(e.Value))
		}
		p("\n")
	}
	if f.Fix != "" {
		p("**Fix:** %s\n", mdText(f.Fix))
	}
}

// mdEscaper backslash-escapes the characters that would let text from the
// capture become Markdown or HTML: a planted "[click here](https://evil)"
// stays literal text in the ticket instead of becoming a link, and "<img>"
// stays text instead of becoming HTML.
var mdEscaper = strings.NewReplacer(
	`\`, `\\`, "`", "\\`", "*", `\*`, "_", `\_`, "[", `\[`, "]", `\]`,
	"<", `&lt;`, ">", `&gt;`, "|", `\|`, "#", `\#`, "!", `\!`,
)

// mdText escapes prose for Markdown.
func mdText(s string) string { return mdEscaper.Replace(clean(s)) }

// mdCode shows a value from the capture as inline code, which renders it
// literally. A backtick inside would end the code span early, so the span
// is fenced with more backticks than the value contains, as CommonMark
// allows. Pipes are escaped because they would split the table cell even
// inside code.
func mdCode(s string) string {
	s = strings.ReplaceAll(clean(s), "|", `\|`)
	if s == "" {
		return ""
	}
	fence := "`"
	for strings.Contains(s, fence) {
		fence += "`"
	}
	pad := ""
	if strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		pad = " "
	}
	return fence + pad + s + pad + fence
}
